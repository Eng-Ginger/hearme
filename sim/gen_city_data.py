"""Generate SYNTHETIC aggregated counts for the HearMe city dashboard (Ajman, UAE).

!!! EVERYTHING THIS SCRIPT WRITES IS SYNTHETIC. !!!
The road grid, schools, bus stops and counts are invented. "Synthetic School A" and
"Synthetic Stop 1" are not real places; no real measurement is used. The only input
taken from elsewhere is the receiver alert rate from the (also simulated) HearMe Monte
Carlo: docs/results/results.json -> dashboard_rates.urgent_per_fast_pass.

Output
  apps/dashboard/api/data/synthetic_counts.csv
      cell_id, lat, lon, hour, fast_passes, urgent_alerts
      One row per (grid cell on a synthetic road, hour 0-23), summed over a synthetic
      30-day month. cell_id follows apps/dashboard/api/grid.py: "<lat_idx>_<lon_idx>",
      idx = floor(deg / 0.001); lat/lon = cell centre.
  apps/dashboard/api/data/synthetic_pois.json
      {"synthetic": true, "note": ..., "pois": [{name, kind, lat, lon}, ...]}
  apps/dashboard/api/data/README_SYNTHETIC.md

Model (all ASSUMPTIONS, chosen only to give the dashboard a plausible shape):
  - Road grid around the centre: arterials every 6 cells (~600 m), local streets every
    2 cells. Two-wheeler flow per hour = base flow (arterial 90 /h, local 25 /h) x a
    delivery-style hourly profile (lunch and evening peaks).
  - Receivers (blind / low-vision pedestrians carrying HearMe) per road cell = background
    0.15 + Gaussian kernels (sigma 150 m) around POIs: schools 2.5 (only 06-15 h, peaks at
    the 07 h and 13-14 h school runs), bus stops 1.5 (scaled by the hourly bus profile).
  - A receiver standing at the roadside sees a fast pass within 5 m with probability
    0.35 per passing rider (kerbside share), during 20 % of the hour (time spent at the kerb).
  - fast_passes ~ Poisson(30 days x flow x receivers x 0.35 x 0.20)
  - urgent_alerts ~ Binomial(fast_passes, p_urgent), p_urgent = share of fast passes within
    5 m that produced >= 1 URGENT alert in the Monte Carlo's HearMe-GPS condition.

Run:  python sim/gen_city_data.py   (after python sim/montecarlo.py)
"""
from __future__ import annotations

import csv
import json
import math
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
OUT_DIR = os.path.join(ROOT, "apps", "dashboard", "api", "data")
RESULTS = os.path.join(ROOT, "docs", "results", "results.json")

CENTER_LAT, CENTER_LON = 25.405, 55.513
CELL = 0.001
HALF_CELLS = 20                     # grid spans +/- 20 cells (~ 4.4 km x 4.0 km)
SEED = 4242
DAYS = 30

ARTERIAL_EVERY, LOCAL_EVERY = 6, 2
FLOW_ARTERIAL, FLOW_LOCAL = 90.0, 25.0                      # riders / h at profile 1.0 (ASSUMPTION)
# delivery-style two-wheeler profile, 0..23 h (ASSUMPTION)
HOUR_FLOW = [0.25, 0.15, 0.08, 0.05, 0.05, 0.10, 0.30, 0.55, 0.55, 0.45, 0.45, 0.65,
             0.95, 1.00, 0.80, 0.60, 0.60, 0.70, 0.85, 1.00, 1.00, 0.90, 0.65, 0.40]
# school presence profile (ASSUMPTION: school day 07-14 h with drop-off / pick-up peaks)
HOUR_SCHOOL = [0, 0, 0, 0, 0, 0, 0.3, 1.0, 0.5, 0.3, 0.3, 0.3, 0.5, 1.0, 0.9, 0.3, 0, 0, 0, 0, 0, 0, 0, 0]
HOUR_BUS = [0.05, 0.02, 0.02, 0.02, 0.05, 0.3, 0.7, 1.0, 0.8, 0.5, 0.5, 0.5,
            0.6, 0.7, 0.8, 0.8, 0.9, 1.0, 0.9, 0.7, 0.5, 0.4, 0.3, 0.15]
REC_BG, REC_SCHOOL, REC_STOP = 0.15, 2.5, 1.5
KERNEL_M = 150.0
P_WITHIN_5M, KERB_TIME = 0.35, 0.20
N_SCHOOLS, N_STOPS = 6, 10

NOTE = ("SYNTHETIC DATA - generated by sim/gen_city_data.py. Invented road grid, invented "
        "schools/stops ('Synthetic School A', 'Synthetic Stop 1', ...) and invented counts around "
        "Ajman's centre coordinates. Not real places, not measurements. Urgent-alert rate taken from "
        "the simulated HearMe Monte Carlo (docs/results/results.json).")


def road_class(i: int, j: int) -> float:
    """Flow at profile 1.0 for the cell at grid offset (i, j); 0 if no road."""
    if i % ARTERIAL_EVERY == 0 or j % ARTERIAL_EVERY == 0:
        return FLOW_ARTERIAL
    if i % LOCAL_EVERY == 0 or j % LOCAL_EVERY == 0:
        return FLOW_LOCAL
    return 0.0


def metres(dlat, dlon):
    k = math.pi / 180.0
    return dlat * k * 6371008.8, dlon * k * 6371008.8 * math.cos(CENTER_LAT * k)


def main():
    with open(RESULTS, encoding="utf-8") as f:
        res = json.load(f)
    p_urgent = float(res["dashboard_rates"]["urgent_per_fast_pass"])
    rng = np.random.default_rng(SEED)
    lat0 = math.floor(CENTER_LAT / CELL + 1e-9)
    lon0 = math.floor(CENTER_LON / CELL + 1e-9)

    # POIs: placed on road cells (schools beside local streets, stops on arterials)
    road_cells = [(i, j) for i in range(-HALF_CELLS + 2, HALF_CELLS - 1) for j in range(-HALF_CELLS + 2, HALF_CELLS - 1)
                  if road_class(i, j) > 0]
    arterial = [c for c in road_cells if road_class(*c) == FLOW_ARTERIAL]
    local = [c for c in road_cells if road_class(*c) == FLOW_LOCAL]
    sch = [local[k] for k in rng.choice(len(local), N_SCHOOLS, replace=False)]
    stp = [arterial[k] for k in rng.choice(len(arterial), N_STOPS, replace=False)]
    pois = []
    for n, (i, j) in enumerate(sch):
        pois.append(dict(name=f"Synthetic School {chr(65 + n)}", kind="school",
                         lat=round((lat0 + i + 0.5) * CELL, 6), lon=round((lon0 + j + 0.5) * CELL, 6), synthetic=True))
    for n, (i, j) in enumerate(stp):
        pois.append(dict(name=f"Synthetic Stop {n + 1}", kind="bus_stop",
                         lat=round((lat0 + i + 0.5) * CELL, 6), lon=round((lon0 + j + 0.5) * CELL, 6), synthetic=True))

    rows = []
    for i in range(-HALF_CELLS, HALF_CELLS + 1):
        for j in range(-HALF_CELLS, HALF_CELLS + 1):
            flow = road_class(i, j)
            if flow == 0:
                continue
            lat_i, lon_i = lat0 + i, lon0 + j
            clat, clon = round((lat_i + 0.5) * CELL, 6), round((lon_i + 0.5) * CELL, 6)
            ks, kb = 0.0, 0.0
            for p in pois:
                dy, dx = metres(p["lat"] - clat, p["lon"] - clon)
                w = math.exp(-0.5 * (dx * dx + dy * dy) / KERNEL_M ** 2)
                if p["kind"] == "school":
                    ks += w
                else:
                    kb += w
            for h in range(24):
                receivers = REC_BG + REC_SCHOOL * ks * HOUR_SCHOOL[h] + REC_STOP * kb * HOUR_BUS[h]
                lam = DAYS * flow * HOUR_FLOW[h] * receivers * P_WITHIN_5M * KERB_TIME
                fp = int(rng.poisson(lam))
                ua = int(rng.binomial(fp, p_urgent)) if fp else 0
                rows.append((f"{lat_i}_{lon_i}", clat, clon, h, fp, ua))

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "synthetic_counts.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["cell_id", "lat", "lon", "hour", "fast_passes", "urgent_alerts"])
        w.writerows(rows)
    with open(os.path.join(OUT_DIR, "synthetic_pois.json"), "w", encoding="utf-8") as f:
        json.dump({"synthetic": True, "note": NOTE, "urgent_per_fast_pass": p_urgent,
                   "urgent_rate_source": "docs/results/results.json dashboard_rates (simulated, HearMe GPS condition)",
                   "pois": pois}, f, indent=1)
    with open(os.path.join(OUT_DIR, "README_SYNTHETIC.md"), "w", encoding="utf-8") as f:
        f.write("# Dashboard data: SYNTHETIC\n\n" + NOTE + "\n\n"
                "- `synthetic_counts.csv`: cell_id, lat, lon, hour, fast_passes, urgent_alerts — one row per road cell "
                "and hour, summed over a synthetic 30-day month. (No comment line inside the CSV so standard CSV "
                "readers, including `apps/dashboard/api/seed.py`, can parse it.)\n"
                "- `synthetic_pois.json`: invented schools and bus stops.\n\n"
                f"Urgent alerts are drawn as Binomial(fast_passes, {p_urgent:.4f}); that rate is the simulated share of "
                "fast passes within 5 m that triggered an URGENT alert in the HearMe-GPS Monte Carlo condition.\n\n"
                "Regenerate: `python sim/montecarlo.py` then `python sim/gen_city_data.py`.\n")
    tot_fp = sum(r[4] for r in rows)
    tot_ua = sum(r[5] for r in rows)
    print(f"SYNTHETIC: {len(rows)} rows, {len({r[0] for r in rows})} cells, {len(pois)} POIs, "
          f"fast_passes={tot_fp}, urgent_alerts={tot_ua}, p_urgent={p_urgent:.4f}")


if __name__ == "__main__":
    main()
