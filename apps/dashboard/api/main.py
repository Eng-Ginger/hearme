"""HearMe City Dashboard API.

Run from the repository root:
    python -m uvicorn apps.dashboard.api.main:app --port 8000

Privacy by construction
-----------------------
* Ingest accepts exactly four fields per record: cell_id, hour, fast_passes,
  urgent_alerts. Any other field (device id, rolling id, precise lat/lon,
  timestamp ...) makes the whole request fail with 422. Nothing else is stored.
* Counts are summed into (cell, hour) buckets on arrival; individual uploads are
  not kept, so the database cannot be replayed into a trace.
* k-anonymity style minimum count: every GET endpoint hides a cell whose total
  (fast_passes + urgent_alerts) for the requested view is below K_MIN, so a single
  pedestrian's (or rider's) few events cannot be singled out on the map.
"""

from __future__ import annotations

import csv
import io
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Annotated, Union

from fastapi import Body, FastAPI, Query
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import HTMLResponse, Response
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, ConfigDict, Field, field_validator

from . import scoring
from .db import Store
from .grid import CELL_DEG, CELL_ID_PATTERN, CENTER_LAT, CENTER_LON, cell_bounds, cell_center, is_cell_id
from .seed import default_db_path, seed_if_empty

K_MIN = 3  # minimum total events before a cell is shown
MAX_COUNT_PER_RECORD = 10_000
MAX_RECORDS_PER_BATCH = 5_000
WEB_DIST = Path(__file__).resolve().parent.parent / "web" / "dist"
DEV_ORIGINS = ["http://localhost:5173", "http://127.0.0.1:5173"]
SYNTHETIC_NOTICE = "SYNTHETIC DATA - generated by the HearMe simulation, not real measurements"


# ---- ingest models ------------------------------------------------------------
class IngestRecord(BaseModel):
    """One aggregated bucket from a receiver. extra='forbid' rejects anything else."""

    model_config = ConfigDict(extra="forbid", strict=True)

    cell_id: str = Field(pattern=CELL_ID_PATTERN, max_length=16,
                         description="Grid cell '<lat_idx>_<lon_idx>', idx = floor(deg / 0.001)")
    hour: int = Field(ge=0, le=23, description="Hour of day, local time, 0-23")
    fast_passes: int = Field(ge=0, le=MAX_COUNT_PER_RECORD)
    urgent_alerts: int = Field(ge=0, le=MAX_COUNT_PER_RECORD)

    @field_validator("cell_id")
    @classmethod
    def _valid_cell(cls, v: str) -> str:
        if not is_cell_id(v):
            raise ValueError("cell_id outside the valid grid range")
        return v


class IngestBatch(BaseModel):
    model_config = ConfigDict(extra="forbid")

    records: list[IngestRecord] = Field(min_length=1, max_length=MAX_RECORDS_PER_BATCH)


class IngestResult(BaseModel):
    accepted: int
    cells: int


# ---- helpers ------------------------------------------------------------------
def _visible_cells(store: Store, hour: int | None, min_total: int) -> tuple[list[dict], int]:
    threshold = max(K_MIN, min_total)
    shown, suppressed = [], 0
    for r in store.cell_totals(hour):
        total = r["fast_passes"] + r["urgent_alerts"]
        if total < threshold:
            suppressed += 1
            continue
        lat, lon = cell_center(r["cell_id"])
        shown.append({
            "cell_id": r["cell_id"],
            "lat": lat,
            "lon": lon,
            "bounds": cell_bounds(r["cell_id"]),
            "fast_passes": r["fast_passes"],
            "urgent_alerts": r["urgent_alerts"],
            "total": total,
        })
    shown.sort(key=lambda c: c["cell_id"])
    return shown, suppressed


HourQ = Annotated[int | None, Query(ge=0, le=23, description="Hour 0-23; omit for all day")]


def create_app(store: Store | None = None, *, seed_on_startup: bool = True,
               web_dist: Path | None = WEB_DIST) -> FastAPI:
    store = store or Store(default_db_path())

    @asynccontextmanager
    async def lifespan(_app: FastAPI):
        if seed_on_startup:
            seed_if_empty(store)
        yield

    app = FastAPI(
        title="HearMe City Dashboard API",
        version="0.1.0",
        description="Anonymous aggregated counts of fast two-wheeler passes and urgent alerts. "
                    + SYNTHETIC_NOTICE,
        lifespan=lifespan,
    )
    app.state.store = store
    app.add_middleware(CORSMiddleware, allow_origins=DEV_ORIGINS, allow_methods=["GET", "POST"],
                       allow_headers=["Content-Type"])

    @app.post("/api/ingest", response_model=IngestResult, tags=["ingest"])
    def ingest(body: Annotated[Union[IngestBatch, list[IngestRecord]], Body()]) -> IngestResult:
        records = body.records if isinstance(body, IngestBatch) else body
        if not records:
            return IngestResult(accepted=0, cells=0)
        store.add_counts((r.cell_id, r.hour, r.fast_passes, r.urgent_alerts) for r in records)
        return IngestResult(accepted=len(records), cells=len({r.cell_id for r in records}))

    @app.get("/api/cells", tags=["read"])
    def cells(hour: HourQ = None,
              min: Annotated[int, Query(ge=0, description=f"Minimum total; never below {K_MIN}")] = K_MIN):
        shown, suppressed = _visible_cells(store, hour, min)
        return {
            "hour": hour,
            "min_total": max(K_MIN, min),
            "suppressed_cells": suppressed,
            "max_fast_passes": max((c["fast_passes"] for c in shown), default=0),
            "max_urgent_alerts": max((c["urgent_alerts"] for c in shown), default=0),
            "cells": shown,
        }

    @app.get("/api/pois", tags=["read"])
    def pois():
        return {"pois": store.pois()}

    @app.get("/api/top", tags=["read"])
    def top(limit: Annotated[int, Query(ge=1, le=100)] = 10, hour: HourQ = None):
        shown, _ = _visible_cells(store, hour, K_MIN)
        ranked = scoring.rank_cells(shown, store.pois())
        return {
            "hour": hour,
            "method": {
                "urgent_weight": scoring.URGENT_WEIGHT,
                "poi_radius_m": scoring.POI_RADIUS_M,
                "kind_weight": scoring.KIND_WEIGHT,
                "formula": "(fast + 3*urgent) * (2 - d/150) * kind_weight",
            },
            "top": ranked[:limit],
        }

    @app.get("/api/export.csv", tags=["read"])
    def export_csv(hour: HourQ = None):
        shown, _ = _visible_cells(store, hour, K_MIN)
        ranked = {r["cell_id"]: r for r in scoring.rank_cells(shown, store.pois())}
        buf = io.StringIO()
        buf.write(f"# {SYNTHETIC_NOTICE}; hour={'all' if hour is None else hour}; "
                  f"cells with total < {K_MIN} suppressed\n")
        w = csv.writer(buf, lineterminator="\n")
        w.writerow(["cell_id", "lat", "lon", "fast_passes", "urgent_alerts", "total", "rank",
                    "score", "nearest_poi", "poi_kind", "distance_m", "intervention"])
        rows = sorted(shown, key=lambda c: (ranked.get(c["cell_id"], {}).get("rank", 10**9), c["cell_id"]))
        for c in rows:
            r = ranked.get(c["cell_id"], {})
            w.writerow([c["cell_id"], c["lat"], c["lon"], c["fast_passes"], c["urgent_alerts"],
                        c["total"], r.get("rank", ""), r.get("score", ""), r.get("nearest_poi", ""),
                        r.get("poi_kind", ""), r.get("distance_m", ""), r.get("intervention", "")])
        name = "hearme_cells_synthetic" + ("" if hour is None else f"_h{hour:02d}") + ".csv"
        return Response(buf.getvalue(), media_type="text/csv; charset=utf-8",
                        headers={"Content-Disposition": f'attachment; filename="{name}"'})

    @app.get("/api/meta", tags=["read"])
    def meta():
        m = store.get_meta()
        return {
            "synthetic": True,
            "notice": SYNTHETIC_NOTICE,
            "data_source": m.get("counts_source", "ingest only"),
            "poi_source": m.get("poi_source"),
            "seeded_at": m.get("seeded_at"),
            "seed_rows": m.get("seed_rows"),
            "counts": store.stats(),
            "k_anonymity_min_total": K_MIN,
            "grid": {"cell_deg": CELL_DEG, "id_format": "<floor(lat/0.001)>_<floor(lon/0.001)>",
                     "center": {"lat": CENTER_LAT, "lon": CENTER_LON}},
            "privacy": "Only (cell_id, hour, fast_passes, urgent_alerts) are accepted; "
                       "any other field is rejected with 422. Cells with fewer than "
                       f"{K_MIN} events are hidden from every read endpoint.",
        }

    if web_dist is not None and (web_dist / "index.html").exists():
        app.mount("/", StaticFiles(directory=web_dist, html=True), name="web")
    else:
        @app.get("/", include_in_schema=False)
        def no_web():
            return HTMLResponse(
                "<h1>HearMe City Dashboard API</h1><p>Web app not built yet: run "
                "<code>npm install && npm run build</code> in apps/dashboard/web. "
                "API docs at <a href='/docs'>/docs</a>.</p>")

    return app


app = create_app()
