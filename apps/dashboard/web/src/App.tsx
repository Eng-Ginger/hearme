import { useEffect, useMemo, useState } from "react";
import { api, type CellsResponse, type Meta, type Metric, type Poi, type Ranked } from "./api";
import MapView, { poiIconHtml, type Focus } from "./MapView";
import { METRIC_LABEL, RAMPS, breaks, hourLabel } from "./scale";

const nf = new Intl.NumberFormat("en");

export default function App() {
  const [metric, setMetric] = useState<Metric>("fast_passes");
  const [hour, setHour] = useState<number | null>(null);
  const [cells, setCells] = useState<CellsResponse | null>(null);
  const [top, setTop] = useState<Ranked[] | null>(null);
  const [pois, setPois] = useState<Poi[]>([]);
  const [meta, setMeta] = useState<Meta | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [focus, setFocus] = useState<Focus | null>(null);

  useEffect(() => {
    api.pois().then(setPois).catch((e) => setError(String(e)));
    api.meta().then(setMeta).catch((e) => setError(String(e)));
  }, []);

  useEffect(() => {
    let alive = true;
    Promise.all([api.cells(hour), api.top(hour, 10)])
      .then(([c, t]) => {
        if (!alive) return;
        setCells(c);
        setTop(t);
        setError(null);
      })
      .catch((e) => {
        if (alive) setError(String(e));
      });
    return () => {
      alive = false;
    };
  }, [hour]);

  const max = cells ? (metric === "fast_passes" ? cells.max_fast_passes : cells.max_urgent_alerts) : 0;
  const classBreaks = useMemo(() => breaks(max), [max]);
  const totals = useMemo(() => {
    const list = cells?.cells ?? [];
    return {
      fast: list.reduce((s, c) => s + c.fast_passes, 0),
      urgent: list.reduce((s, c) => s + c.urgent_alerts, 0),
    };
  }, [cells]);
  const minTotal = cells?.min_total ?? meta?.k_anonymity_min_total ?? 3;

  return (
    <div className="app">
      <header className="topbar">
        <div className="brand">
          <span className="logo" aria-hidden="true">
            <svg viewBox="0 0 32 32" width="32" height="32">
              <rect width="32" height="32" rx="7" fill="#ffd166" />
              <path d="M9 20a7 7 0 0 1 14 0" stroke="#0b3d5c" strokeWidth="3" fill="none" strokeLinecap="round" />
              <circle cx="16" cy="21" r="2.5" fill="#0b3d5c" />
            </svg>
          </span>
          <div>
            <h1>HearMe City Dashboard</h1>
            <p className="subtitle">Fast two-wheelers and near misses around schools and bus stops · Ajman, UAE</p>
          </div>
        </div>
        <span className="proto-tag">WFEO Hackathon 2027 prototype</span>
      </header>

      <p className="synthetic-banner" role="note">
        <span className="banner-icon" aria-hidden="true">!</span>
        <span>
          <strong>SYNTHETIC DATA</strong> — generated by the HearMe simulation, not real measurements
          {meta && <span className="banner-src"> · Source: {meta.data_source}</span>}
        </span>
      </p>

      {error && (
        <p className="error" role="alert">
          Could not load data from the API ({error}). Is the server running on port 8000?
        </p>
      )}

      <main className="layout">
        <section className="map-wrap" aria-label="Map of Ajman with grid cells coloured by count">
          <MapView cells={cells?.cells ?? []} pois={pois} metric={metric} classBreaks={classBreaks} focus={focus} />
          <div className="legend">
            <h2 className="legend-title">
              {METRIC_LABEL[metric]}
              <span className="muted"> · {hourLabel(hour)}</span>
            </h2>
            <ul className="ramp" aria-label="Colour scale, events per cell">
              {RAMPS[metric].map((col, i) => {
                const lo = i === 0 ? 1 : classBreaks[i - 1] + 1;
                const hi = Math.min(classBreaks[i], max);
                if (max > 0 && lo > hi) return null;
                const text = max === 0 ? "–" : lo === hi ? nf.format(hi) : `${nf.format(lo)}–${nf.format(hi)}`;
                return (
                  <li key={col}>
                    <span className="swatch" style={{ background: col }} />
                    <span>{text}</span>
                  </li>
                );
              })}
            </ul>
            <ul className="legend-pois">
              <li>
                <span dangerouslySetInnerHTML={{ __html: poiIconHtml("school") }} /> Synthetic school
              </li>
              <li>
                <span dangerouslySetInnerHTML={{ __html: poiIconHtml("bus_stop") }} /> Synthetic bus stop
              </li>
              <li className="muted">Cells with &lt; {minTotal} events are hidden</li>
            </ul>
          </div>
        </section>

        <aside className="panel" aria-label="Controls and ranking">
          <section className="card controls" aria-label="Map controls">
            <fieldset className="segmented">
              <legend>Colour cells by</legend>
              <div className="seg-row">
                {(["fast_passes", "urgent_alerts"] as Metric[]).map((m) => (
                  <label key={m} className={metric === m ? "active" : ""}>
                    <input
                      type="radio"
                      name="metric"
                      value={m}
                      checked={metric === m}
                      onChange={() => setMetric(m)}
                    />
                    {m === "fast_passes" ? "Fast passes" : "Urgent alerts"}
                  </label>
                ))}
              </div>
            </fieldset>

            <div className="hour">
              <div className="hour-head">
                <label htmlFor="hour">Time of day</label>
                <output htmlFor="hour" className="hour-value">
                  {hourLabel(hour)}
                </output>
              </div>
              <input
                id="hour"
                type="range"
                min={-1}
                max={23}
                step={1}
                value={hour ?? -1}
                aria-valuetext={hourLabel(hour)}
                onChange={(e) => {
                  const v = Number(e.target.value);
                  setHour(v < 0 ? null : v);
                }}
              />
              <div className="hour-ticks" aria-hidden="true">
                <span>All day</span>
                <span>06</span>
                <span>12</span>
                <span>18</span>
                <span>23</span>
              </div>
              {hour !== null && (
                <button type="button" className="link-btn" onClick={() => setHour(null)}>
                  Reset to all day
                </button>
              )}
            </div>

            <dl className="stats">
              <div>
                <dt>Fast passes</dt>
                <dd>{nf.format(totals.fast)}</dd>
              </div>
              <div>
                <dt>Urgent alerts</dt>
                <dd>{nf.format(totals.urgent)}</dd>
              </div>
              <div>
                <dt>Cells shown</dt>
                <dd>
                  {nf.format(cells?.cells.length ?? 0)}
                  {cells && cells.suppressed_cells > 0 && (
                    <span className="muted tiny"> +{cells.suppressed_cells} hidden</span>
                  )}
                </dd>
              </div>
            </dl>

            <a className="btn" href={api.exportUrl(hour)} download>
              <svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true">
                <path
                  fill="currentColor"
                  d="M12 3a1 1 0 0 1 1 1v9.6l3.3-3.3 1.4 1.4L12 17.4l-5.7-5.7 1.4-1.4 3.3 3.3V4a1 1 0 0 1 1-1zM5 19h14v2H5z"
                />
              </svg>
              Export CSV · {hourLabel(hour)}
            </a>
          </section>

          <section className="card ranking" aria-labelledby="rank-h">
            <h2 id="rank-h">Top 10 sites for a crossing or speed measure</h2>
            <p className="muted small">Within 150 m of a school or bus stop · {hourLabel(hour)} · select to show on map</p>
            {top === null ? (
              <p className="muted">Loading…</p>
            ) : top.length === 0 ? (
              <p className="muted">No cell near a school or stop passes the minimum count for this hour.</p>
            ) : (
              <ol className="rank-list">
                {top.map((t) => (
                  <li key={t.cell_id}>
                    <button
                      type="button"
                      className="rank-item"
                      aria-current={focus?.cellId === t.cell_id ? "true" : undefined}
                      aria-label={`Rank ${t.rank}: ${t.intervention} near ${t.nearest_poi}, ${Math.round(
                        t.distance_m,
                      )} metres away, ${t.fast_passes} fast passes, ${t.urgent_alerts} urgent alerts, score ${t.score.toFixed(
                        1,
                      )}. Show on map.`}
                      onClick={() => setFocus({ lat: t.lat, lon: t.lon, cellId: t.cell_id, nonce: Date.now() })}
                    >
                      <span className="rank-no">{t.rank}</span>
                      <span className="rank-body">
                        <span className="rank-title">
                          {t.nearest_poi}
                          <span className="muted small"> · {Math.round(t.distance_m)} m</span>
                        </span>
                        <span className={`intervention iv-${t.poi_kind}`}>{t.intervention}</span>
                        <span className="rank-nums small">
                          {t.fast_passes} fast · {t.urgent_alerts} urgent
                        </span>
                      </span>
                      <span className="rank-score">
                        <span className="tiny muted">score</span>
                        {t.score.toFixed(0)}
                      </span>
                    </button>
                  </li>
                ))}
              </ol>
            )}
          </section>

          <section className="card notes" aria-labelledby="notes-h">
            <h2 id="notes-h">How to read this</h2>
            <p className="small">
              <strong>Score</strong> = (fast passes + 3 × urgent alerts) × proximity (2× at the school or stop, 1× at
              150 m) × 1.25 near schools.
            </p>
            <p className="small">
              <strong>Privacy.</strong> Receivers upload only anonymous counts per ~100 m cell and hour. Uploads that
              carry a device, rolling or precise-position field are rejected. Cells with fewer than {minTotal} events
              are hidden so no one can be singled out.
            </p>
            {meta && (
              <p className="small muted">
                {nf.format(meta.counts.rows)} cell-hour records · {nf.format(meta.counts.cells)} cells ·{" "}
                {nf.format(meta.counts.pois)} synthetic places
              </p>
            )}
          </section>
        </aside>
      </main>
    </div>
  );
}
