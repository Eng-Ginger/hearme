"""Regenerate the static inputs (dashboard JSON, credits page), build the site exactly as Vercel does,
scan it for secrets and report sizes. Output: apps/lab/dist (copied to deploy/hearme-lab/).

- HearMe Lab (apps/lab): /, /phone.html (same origin, so BroadcastChannel links the phone to the Lab)
- City dashboard, read-only: /dashboard/ with responses precomputed from the real FastAPI app
- /credits.html generated from apps/lab/ATTRIBUTION.md
- vercel.json, secrets scan, size report

Run from the repo root:  python tools/build_deploy.py
"""
import json
import os
import re
import shutil
import subprocess
import sys

import markdown

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAB = os.path.join(ROOT, "apps", "lab")
DIST = os.path.join(LAB, "dist")
OUT = os.path.join(ROOT, "deploy", "hearme-lab")
NPX = "npx.cmd" if os.name == "nt" else "npx"
NPM = "npm.cmd" if os.name == "nt" else "npm"


def run(cmd, cwd=ROOT, env=None):
    p = subprocess.run(cmd, cwd=cwd, env={**os.environ, **(env or {})}, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if p.returncode:
        print(p.stdout[-2000:], p.stderr[-2000:]); sys.exit(f"failed: {' '.join(cmd)}")


# 1. Precompute the read-only dashboard data from the real API (committed, so Vercel needs no Python)
sys.path.insert(0, ROOT)
from fastapi.testclient import TestClient  # noqa: E402
from apps.dashboard.api.main import create_app  # noqa: E402

data = os.path.join(ROOT, "apps", "dashboard", "web", "public", "data")
os.makedirs(data, exist_ok=True)
with TestClient(create_app()) as c:
    for hour in [None] + list(range(24)):
        q, tag = ("" if hour is None else f"hour={hour}"), ("all" if hour is None else str(hour))
        json.dump(c.get(f"/api/cells?{q}").json(), open(f"{data}/cells_{tag}.json", "w"), separators=(",", ":"))
        json.dump(c.get(f"/api/top?limit=10&{q}").json(), open(f"{data}/top_{tag}.json", "w"), separators=(",", ":"))
        open(f"{data}/export_{tag}.csv", "w", encoding="utf-8", newline="").write(c.get(f"/api/export.csv?{q}").text)
    json.dump(c.get("/api/pois").json(), open(f"{data}/pois.json", "w"))
    meta = c.get("/api/meta").json()
    meta["notice"] = "Synthetic demo data generated by the HearMe simulation. Read-only static demo; not real measurements."
    json.dump(meta, open(f"{data}/meta.json", "w"))

# 3. Credits page from ATTRIBUTION.md
att = open(os.path.join(LAB, "ATTRIBUTION.md"), encoding="utf-8").read()
att = re.sub(r"(?<!\()(https?://[^\s|)]+)", r"<\1>", att)
body = markdown.markdown(att, extensions=["tables"])
open(os.path.join(LAB, "public", "credits.html"), "w", encoding="utf-8").write(f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1"><title>HearMe Lab: credits</title>
<style>body{{font-family:"Segoe UI",system-ui,sans-serif;max-width:980px;margin:32px auto;padding:0 20px;line-height:1.5;color:#1d1d1f}}
table{{border-collapse:collapse;width:100%;font-size:14px;margin:10px 0 22px}}th,td{{border:1px solid #ddd;padding:6px 8px;text-align:left;vertical-align:top}}
th{{background:#f4efd9}}a{{color:#0b4f9c;word-break:break-all}}h1{{border-bottom:3px solid #f2c200;padding-bottom:6px}}</style></head>
<body><p><a href="/">← Back to HearMe Lab</a></p>{body}
<p>Team: Mohammed Shehadeh (lead), M. Ghaith Ali, Moundir Mekkaoui · WFEO Hackathon 2027 · Challenge 1: Inclusive Mobility</p></body></html>""")

# 4. The same build Vercel runs (root vercel.json: npm ci + npm run build:vercel -> apps/lab/dist)
run([NPM, "run", "build:vercel"])

# 5. Secrets scan
bad = []
for dp, _, fs in os.walk(DIST):
    for f in fs:
        path = os.path.join(dp, f)
        if f.startswith(".env") or f.endswith((".pem", ".key")):
            bad.append(path)
        elif f.endswith((".js", ".html", ".json", ".css", ".csv")):
            t = open(path, encoding="utf-8", errors="ignore").read()
            for pat in (r"BEGIN [A-Z ]*PRIVATE KEY", r"sk-[A-Za-z0-9]{20,}", r"ghp_[A-Za-z0-9]{20,}", r"AKIA[0-9A-Z]{16}", r"(?i)api[_-]?key\s*[:=]\s*['\"][A-Za-z0-9]{16,}"):
                if re.search(pat, t):
                    bad.append(f"{path}: {pat}")
if bad:
    sys.exit("possible secrets:\n" + "\n".join(bad))

# 6. Copy to deploy/hearme-lab and report sizes
if os.path.exists(OUT):
    shutil.rmtree(OUT)
shutil.copytree(DIST, OUT)
size = lambda p: os.path.getsize(p)
total = sum(size(os.path.join(dp, f)) for dp, _, fs in os.walk(OUT) for f in fs)
idx = open(os.path.join(OUT, "index.html"), encoding="utf-8").read()
first = [os.path.join(OUT, "index.html")] + [os.path.join(OUT, m.lstrip("/")) for m in re.findall(r'(?:src|href)="(/assets/[^"]+)"', idx)]
first += [os.path.join(OUT, "assets", "polyhaven", f) for f in os.listdir(os.path.join(OUT, "assets", "polyhaven")) if f.endswith(".webp")]
first.append(os.path.join(OUT, "assets", "polyhaven", "qwantani_late_afternoon_puresky_1k.hdr"))
fl = sum(size(p) for p in first if os.path.exists(p))
print(f"deploy dir: {OUT}")
print(f"total {total / 1e6:.1f} MB; first load (HTML + JS/CSS + textures + 1k HDRI, uncompressed) {fl / 1e6:.2f} MB")
print("secrets scan: clean (the public test fleet key in the JS bundle is published in the spec on purpose)")
