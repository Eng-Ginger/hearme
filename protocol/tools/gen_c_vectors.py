"""Turn protocol/test_vectors.json into a C header for the C codec test.

Run:  python protocol/tools/gen_c_vectors.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
src = json.load(open(os.path.join(HERE, "..", "test_vectors.json"), encoding="utf-8"))
TYPES = ["e_bike", "e_scooter", "tuk_tuk", "car", "bus", "bus_stop", "crossing", "school_zone", "motorcycle"]
DOORS = ["front", "middle", "rear", "unknown"]


def carr(hexs):
    b = bytes.fromhex(hexs)
    return "{" + ",".join(f"0x{x:02x}" for x in b) + "}", len(b)


lines = ["/* GENERATED by protocol/tools/gen_c_vectors.py from test_vectors.json - do not edit */",
         "#include <stdint.h>",
         "typedef struct { const char *name; int valid; const char *failure; uint32_t epoch;",
         "  uint8_t payload[40]; int len; uint8_t adv[40]; int adv_len;",
         "  int type; uint8_t rid[4]; int speed_raw, heading_raw, braking, gps_valid, reversing, has_pos;",
         "  int32_t lat_e7, lon_e7; const char *route; int door, ramp; int short_code; const char *name_f; } hm_vec_t;",
         "static const hm_vec_t HM_VECS[] = {"]
for v in src["vectors"]:
    pay, n = carr(v["payload_hex"])
    if v["valid"]:
        f = v["fields"]
        adv, an = carr(v["adv_hex"])
        rid = "{" + ",".join(f"0x{x:02x}" for x in bytes.fromhex(f["rolling_id"])) + "}"
        haspos = f["lat_e7"] is not None
        lines.append(
            f'  {{"{v["name"]}", 1, "", {v["epoch"]}u, {pay}, {n}, {adv}, {an}, {TYPES.index(f["type"])}, {rid}, '
            f'{f["speed_raw"]}, {f["heading_raw"]}, {int(f["braking"])}, {int(f["gps_valid"])}, {int(f["reversing"])}, {int(haspos)}, '
            f'{f["lat_e7"] or 0}, {f["lon_e7"] or 0}, "{f.get("route", "")}", {DOORS.index(f.get("door", "unknown"))}, '
            f'{int(f.get("ramp", False))}, {f.get("short_code", 0)}, "{f.get("name", "")}"}},')
    else:
        lines.append(f'  {{"{v["name"]}", 0, "{v["failure"]}", {v["epoch"]}u, {pay}, {n}, {{0}}, 0, 0, {{0}}, '
                     f'0,0,0,0,0,0, 0,0, "", 3, 0, 0, ""}},')
lines.append("};")
lines.append(f"#define HM_NVECS {len(src['vectors'])}")
out = os.path.join(HERE, "..", "c", "test", "test_vectors_gen.h")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote", os.path.normpath(out))
